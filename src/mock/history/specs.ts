/**
 * The 90-day history: 46 resolved incidents between Sat 22 Aug and Fri 20 Nov
 * 2026, in the brief's mix, plus the incidents open at the demo start.
 *
 * Each spec states what happened physically (effects), when it was raised,
 * how quickly someone acknowledged it, and how it was resolved. Everything
 * shown in the app, including response times and water lost, is derived
 * from these specs; nothing is typed again elsewhere.
 *
 * Acknowledgement delays are chosen so the medians match the research: 6 min
 * in business hours (weekdays 08:00 to 18:00 local) and 23 min after hours,
 * with a visible tail.
 */
import type { IncidentCategory, ResolutionCode } from "@/domain/building";
import type { Severity } from "@/domain/common";
import type { Effect } from "@/mock/signals/effects";

export type LocalStamp = [y: number, m: number, d: number, h: number, mi: number];

export interface AlertSpec {
  rule: string;
  device: string; // tag
  /** Minutes after the incident opened. */
  afterMin: number;
  value: number;
  summary: string;
}

export interface HistorySpec {
  key: string;
  category: IncidentCategory;
  buildingId: string;
  /** Incident opens, building local time. */
  at: LocalStamp;
  severity: Severity;
  /** Severity raised to critical after this many minutes. */
  criticalAfterMin?: number;
  title: string;
  location: string;
  level: string | null; // level short
  alerts: AlertSpec[];
  /** null: never acknowledged (auto-resolved when the condition cleared). */
  ack: { afterMin: number; by: string } | null;
  dispatch?: { afterMin: number; by: string; to: string; etaMin: number };
  isolate?: { afterMin: number; by: string };
  /** Absent for incidents still open at the demo start. */
  resolve?: { afterMin: number; by: string; code: ResolutionCode; cause: string; action: string };
  notes?: Array<{ afterMin: number; by: string; text: string }>;
  photos?: Array<{ afterMin: number; by: string; caption: string }>;
  damage?: string;
  /** Physical effects, given the opening time in UTC and a device-id helper. */
  effects: (open: number, dev: (tag: string) => string) => Effect[];
  /** Water lost, if a meter measured it: rate and the span it ran, relative to opening. null toMin: still running. */
  water?: { rateLpm: number; fromMin: number; toMin: number | null; meter: string };
  /** Absolute opening time, when it is derived from the signals rather than stated. */
  openedAtUtc?: number;
  /** Absolute acknowledgement time, when stated as a clock time. */
  ackAtUtc?: number;
  /** Still open at the demo start. */
  openAtStart?: boolean;
}

