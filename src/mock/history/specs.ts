const wet = (dev: string, from: number, to: number): Effect => ({ kind: "wet", deviceId: dev, from, to });
const leak = (b: string, meters: string[], rate: number, from: number, to: number, note: string, rampMin = 2): Effect => ({
  kind: "leak",
  buildingId: b,
  meterTags: meters,
  rateLpm: rate,
  rampMin,
  from,
  to,
  note,
});

